#!/bin/sh
# Generates a local .env with random secrets. Never commit .env.
# Usage: sh scripts/init-env.sh [--dev]   (--dev also creates the hlcrm_test database for running tests)
set -eu
umask 077
dev=false
[ "${1:-}" = "--dev" ] && dev=true
if [ -f .env ]; then
  echo ".env already exists; leaving it alone. Delete it first to regenerate (this also needs a fresh database volume)."
  exit 0
fi
rand() { openssl rand -base64 "$1" | tr -d '\n/+=' | cut -c1-"$2"; }
pg=$(rand 32 32); mig=$(rand 32 32); app=$(rand 32 32); mk=$(openssl rand -base64 32); svc=$(rand 48 48)
if [ -z "$pg" ] || [ -z "$mig" ] || [ -z "$app" ] || [ -z "$mk" ] || [ -z "$svc" ]; then
  echo "Could not generate secrets (is openssl installed?)." >&2
  exit 1
fi
{
  echo "# Generated by scripts/init-env.sh for local development. Do not commit."
  echo "POSTGRES_PASSWORD=$pg"
  echo "HLCRM_MIGRATOR_PASSWORD=$mig"
  echo "HLCRM_APP_PASSWORD=$app"
  echo "# 32 random bytes, base64. Wraps each workspace's data encryption key. Losing it makes restricted fields unreadable."
  echo "HLCRM_MASTER_KEY=$mk"
  echo "# Shared by the api and mcp services; used only once MCP_PUBLIC_URL turns on OAuth for MCP (docs/mcp/oauth.md)."
  echo "MCP_SERVICE_SECRET=$svc"
  echo "# The address you open the web UI at. People sign-in and the server-printed sign-in link need it."
  echo "# http is accepted only for localhost; use your https address when you put the CRM on a server."
  echo "PUBLIC_URL=http://localhost:8787"
  echo ""
  echo "# Optional settings, all off or at their defaults until set (each is explained in .env.example):"
  echo "# WEB_UI=true                         serve the web UI at PUBLIC_URL; false for an API-only deployment"
  echo "# WEB_UI_DIR=                         another build of the web UI (default: the one in the image)"
  echo "# MCP_PUBLIC_URL=                     turns on OAuth for the remote MCP servers (needs PUBLIC_URL and MCP_SERVICE_SECRET above)"
  echo "# PASSWORD_MIN_STRENGTH=3             how hard to guess new passwords must be, 0 (off) to 4; 4 is stricter"
  echo "# AUTOMATION_ACTIONS_PER_HOUR=5000    automation caps per workspace and hour (docs/automations.md)"
  echo "# AUTOMATION_HTTP_PER_HOUR=500"
  echo "# AUTOMATION_EMAILS_PER_HOUR=200"
  echo "# AUTOMATION_EMAILS_PER_AUTOMATION_HOUR=50"
  echo "# AUTOMATION_EMAILS_PER_RECIPIENT_DAY=5"
  if [ "$dev" = true ]; then
    echo "# Development only: create the hlcrm_test database on first init of the Postgres volume."
    echo "HLCRM_CREATE_TEST_DB=true"
  fi
} > .env.tmp
mv .env.tmp .env
chmod 600 .env
echo "Wrote .env with fresh random secrets."
